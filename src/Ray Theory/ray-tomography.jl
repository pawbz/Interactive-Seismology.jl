        function pertAt(xw, zw){
          const fx = Math.max(0, Math.min(PNX-1-1e-9, (xw-XMIN)/(XMAX-XMIN)*(PNX-1)));
          const fz = Math.max(0, Math.min(PNZ-1-1e-9, (zw-ZMIN)/(ZMAX-ZMIN)*(PNZ-1)));
